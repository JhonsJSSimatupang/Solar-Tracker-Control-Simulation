function modelPath = build_solar_tracker_model()
% BUILD_SOLAR_TRACKER_MODEL  Create the baseline dual-axis Simulink model.
%
% The generated model uses only standard Simulink blocks:
%   target/measured angles -> PI controllers -> limited axis plants
%
% This is the Gate G3 baseline. Simscape Multibody and Simscape Electrical
% can replace the axis plants later without changing the top-level interface.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(genpath(fullfile(projectRoot, 'src')));
run(fullfile(projectRoot, 'src', 'initialization', 'setup_project.m'));

modelName = 'solar_tracker';
modelPath = fullfile(projectRoot, 'models', [modelName '.slx']);

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
if isfile(modelPath)
    delete(modelPath);
end

new_system(modelName);
open_system(modelName);
modelWorkspace = get_param(modelName, 'ModelWorkspace');
% The default input covers the full stop time so that From Workspace never
% extrapolates outside the data range. run_project replaces these signals
% with the real solar trajectory before simulating.
defaultTime = [0; cfg.simulation.durationHours * 3600];
assignin(modelWorkspace, 'targetAzimuthInput', ...
    timeseries([0; 0], defaultTime));
assignin(modelWorkspace, 'targetTiltInput', ...
    timeseries([0; 0], defaultTime));
set_param(modelName, ...
    'Solver', 'ode4', ...
    'FixedStep', 'cfg.simulation.energySampleTime', ...
    'StopTime', 'cfg.simulation.durationHours * 3600');

add_from_workspace(modelName, 'TargetAzimuth', 'targetAzimuthInput', [30 55 140 85]);
add_from_workspace(modelName, 'TargetTilt', 'targetTiltInput', [30 275 140 305]);

add_axis_controller(modelName, 'Azimuth', 110, ...
    'cfg.controller.azimuth', 'cfg.tracker.azimuth');
add_axis_controller(modelName, 'Tilt', 330, ...
    'cfg.controller.elevation', 'cfg.tracker.elevation');

add_block('simulink/Sinks/Out1', [modelName '/AzimuthOutput'], ...
    'Position', [730 110 760 130]);
add_block('simulink/Sinks/Out1', [modelName '/TiltOutput'], ...
    'Position', [730 330 760 350]);
add_block('simulink/Sinks/Out1', [modelName '/AzimuthError'], ...
    'Position', [730 170 760 190]);
add_block('simulink/Sinks/Out1', [modelName '/TiltError'], ...
    'Position', [730 390 760 410]);

add_line(modelName, 'TargetAzimuth/1', 'AzimuthErrorSum/1');
add_line(modelName, 'TargetTilt/1', 'TiltErrorSum/1');

wire_axis(modelName, 'Azimuth', 'AzimuthErrorSum', 'AzimuthController', ...
    'AzimuthPlant', 'AzimuthOutput', 'AzimuthError');
wire_axis(modelName, 'Tilt', 'TiltErrorSum', 'TiltController', ...
    'TiltPlant', 'TiltOutput', 'TiltError');

save_system(modelName, modelPath);
% Close the model after saving. Leaving it open and dirty blocks later
% close_system calls in the same session and produces a confusing
% "model has been changed" warning in the middle of a test run.
close_system(modelName, 0);
fprintf('Created baseline model: %s\n', modelPath);
end

function add_from_workspace(modelName, blockName, variableName, position)
add_block('simulink/Sources/From Workspace', ...
    [modelName '/' blockName], ...
    'VariableName', variableName, ...
    'Interpolate', 'on', ...
    'Position', position);
end

function add_axis_controller(modelName, axisName, y, controller, tracker)
sumName = [axisName 'ErrorSum'];
controllerName = [axisName 'Controller'];
plantName = [axisName 'Plant'];

add_block('simulink/Math Operations/Sum', [modelName '/' sumName], ...
    'Inputs', '+-', 'Position', [100 y 130 y + 30]);

add_block('built-in/Subsystem', [modelName '/' controllerName], ...
    'Position', [220 y - 20 390 y + 50]);
add_block('simulink/Ports & Subsystems/In1', ...
    [modelName '/' controllerName '/Error'], ...
    'Position', [30 65 60 85]);
add_block('simulink/Ports & Subsystems/Out1', ...
    [modelName '/' controllerName '/Command'], ...
    'Position', [360 65 390 85]);
add_block('simulink/Math Operations/Gain', ...
    [modelName '/' controllerName '/Kp'], ...
    'Gain', [controller '.Kp'], ...
    'Position', [100 20 160 50]);
add_block('simulink/Math Operations/Gain', ...
    [modelName '/' controllerName '/Ki'], ...
    'Gain', [controller '.Ki'], ...
    'Position', [100 110 160 140]);
add_block('simulink/Continuous/Integrator', ...
    [modelName '/' controllerName '/Integral'], ...
    'InitialCondition', '0', ...
    'Position', [200 110 230 140]);
add_block('simulink/Math Operations/Sum', ...
    [modelName '/' controllerName '/PI_Sum'], ...
    'Inputs', '++', ...
    'Position', [270 55 300 95]);
add_block('simulink/Discontinuities/Saturation', ...
    [modelName '/' controllerName '/VoltageLimit'], ...
    'UpperLimit', [controller '.outputMax'], ...
    'LowerLimit', [controller '.outputMin'], ...
    'Position', [320 55 350 95]);
controllerPath = [modelName '/' controllerName];
add_line(controllerPath, 'Error/1', 'Kp/1');
add_line(controllerPath, 'Error/1', 'Ki/1');
add_line(controllerPath, 'Ki/1', 'Integral/1');
add_line(controllerPath, 'Kp/1', 'PI_Sum/1');
add_line(controllerPath, 'Integral/1', 'PI_Sum/2');
add_line(controllerPath, 'PI_Sum/1', 'VoltageLimit/1');
add_line(controllerPath, 'VoltageLimit/1', 'Command/1');

add_block('simulink/Math Operations/Gain', ...
    [modelName '/' axisName '_PlantGain'], ...
    'Gain', ['1 / (' tracker '.gearRatio * ' tracker '.gearEfficiency)'], ...
    'Position', [550 y 610 y + 30]);
add_block('simulink/Continuous/Integrator', ...
    [modelName '/' plantName], ...
    'Position', [650 y 700 y + 30]);

end

function wire_axis(modelName, axisName, errorSum, controllerName, plantName, outputName, errorOutputName)
add_line(modelName, [errorSum '/1'], [controllerName '/1']);
add_line(modelName, [controllerName '/1'], [axisName '_PlantGain/1']);
add_line(modelName, [axisName '_PlantGain/1'], [plantName '/1']);
add_line(modelName, [plantName '/1'], [outputName '/1']);
add_line(modelName, [plantName '/1'], [errorSum '/2']);
add_line(modelName, [errorSum '/1'], [errorOutputName '/1']);
end
